#!/usr/bin/env python3
"""Generate GDScript stub modules (one per C file) from tools/symbols.json.

Each C function becomes a `static func` with the same name. Stubs of functions in
the closed blocking list (tools/blocking.json) are coroutines (they contain an
await), so callers' `await`s type-check from day one (REDUNDANT_AWAIT is an
error in this project). Existing module files are never overwritten.

usage: tools/gen_stubs.py [--force MODULE...]
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
GODOT = os.path.join(ROOT, "godot", "rogue")

# C file -> GDScript class_name
MODULES = {
    "armor.c": "Armor", "chase.c": "Chase", "command.c": "Command", "daemon.c": "Daemon",
    "daemons.c": "Daemons", "fight.c": "Fight", "init.c": "Init", "io.c": "Io",
    "list.c": "List", "main.c": "Main", "misc.c": "Misc", "monsters.c": "Monsters",
    "move.c": "Move", "new_level.c": "NewLevel", "options.c": "Options", "pack.c": "Pack",
    "passages.c": "Passages", "potions.c": "Potions", "rings.c": "Rings", "rip.c": "Rip",
    "rooms.c": "Rooms", "save.c": "Save", "scrolls.c": "Scrolls", "sticks.c": "Sticks",
    "things.c": "Things", "weapons.c": "Weapons", "wizard.c": "Wizard",
    "mach_dep.c": "MachDep", "mdport.c": "Mdport",
}
# Functions whose home in the port is not their C file.
MOVED = {"rnd": "RogueBase", "roll": "RogueBase"}
# Platform functions that the port does not need (signals, setuid, files of the C
# save format, DES crypt, shell, terminal modes...). Not stubbed.
SKIP = {
    "mdport.c": None,   # only the functions in KEEP_MDPORT are ported
    "state.c": "all", "xcrypt.c": "all", "vers.c": "all",
}
KEEP_MDPORT = {"md_readchar", "md_hasclreol", "md_getusername", "md_gethomedir",
               "md_getpid", "md_getuid", "md_unlink", "md_shellescape", "md_sleep",
               "md_crypt", "md_getpass", "md_erasechar", "md_killchar", "md_raw_standout",
               "md_raw_standend", "md_normaluser", "md_init", "md_getrealname",
               "md_onsignal_default", "md_onsignal_exit", "md_onsignal_autosave",
               "md_ignoreallsignals", "md_tstphold", "md_tstpresume", "md_tstpsignal",
               "md_chmod", "md_unlink_open_file", "md_getshell", "md_dsuspchar",
               "md_setdsuspchar", "md_suspchar", "md_setsuspchar"}
RENAME = {"range": "range_", "str": "str_", "len": "len_", "char": "char_", "in": "in_",
          "class": "class_", "var": "var_", "func": "func_", "match": "match_",
          "pass": "pass_", "print": "print_", "type": "type_", "max": "max_", "min": "min_",
          "abs": "abs_", "seed": "seed_", "exp": "exp_", "sign": "sign_", "is": "is_",
          "as": "as_", "not": "not_"}


# C functions whose names clash with Godot Object methods or built-in functions.
RENAME_FUNC = {"call": "call_", "sign": "sign_"}


def stub(name, info, blocking):
    gd_name = RENAME_FUNC.get(name, name)
    params = [RENAME.get(p, p) for p in info["params"] if p]
    if name in ("runners", "doctor", "swander", "stomach", "rollwand", "unconfuse",
                "nohaste", "unsee", "sight", "land", "come_down", "visuals"):
        params = ["_arg: int = 0"]
    elif name in ("msg", "addmsg"):
        params = ["fmt: String", "args: Array = []"]
    elif name == "doadd":
        params = ["fmt: String", "args: Array"]
    ret = info["type"].split("(")[0].strip()
    lines = [f"## {info['file']}: {info['type'].replace('(', name + '(', 1)}"]
    sig = ", ".join(params)
    lines.append(f"static func {gd_name}({sig}):")
    if blocking:
        lines.append(f"\tawait _todo(\"{name}\")")
    else:
        lines.append(f"\t_todo_sync(\"{name}\")")
    if ret != "void":
        if ret.endswith("*"):
            lines.append("\treturn null")
        elif ret == "bool":
            lines.append("\treturn false")
        else:
            lines.append("\treturn 0")
    return "\n".join(lines)


def main():
    force = set(sys.argv[2:]) if len(sys.argv) > 1 and sys.argv[1] == "--force" else set()
    sym = json.load(open(os.path.join(ROOT, "tools", "symbols.json")))
    blocking = set(json.load(open(os.path.join(ROOT, "tools", "blocking.json")))["blocking"])
    by_file = {}
    for name, info in sym["functions"].items():
        f = info["file"]
        if SKIP.get(f) == "all" or name in MOVED:
            continue
        if f == "mdport.c" and name not in KEEP_MDPORT:
            continue
        by_file.setdefault(f, []).append((info["line"], name, info))
    os.makedirs(GODOT, exist_ok=True)
    for f, funcs in sorted(by_file.items()):
        cls = MODULES[f]
        path = os.path.join(GODOT, f[:-2] + ".gd")
        if os.path.exists(path) and cls not in force:
            continue
        out = [f"## {f} (STUB: not yet translated; generated by tools/gen_stubs.py)",
               f"class_name {cls}", "extends RogueBase", ""]
        for _, name, info in sorted(funcs):
            out += ["", stub(name, info, name in blocking)]
        with open(path, "w") as fh:
            fh.write("\n".join(out) + "\n")
        print("wrote", path)


if __name__ == "__main__":
    main()
